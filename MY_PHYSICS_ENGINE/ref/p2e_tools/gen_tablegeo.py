import os; W0=os.environ.get('PP2_WORK','.')
#!/usr/bin/env python3
"""Generates data/pp2_tables.json and core/sim/pp2_tablegeo.hpp from the game's own files
(data.unity3d -> sharedassets0.assets + .resS). Run tools/ufs.py on data.unity3d first (dir 'dat').
Every number comes from the serialized scene: Transform chain x collider mesh / box. Nothing is fitted."""
import sys,json,os; sys.path.insert(0,os.path.dirname(__file__))
from export_tables import *
C=collect()
TABLES=[('TableLvl1-4Model','Lvl1_4','RockTransformsLevel3'),('TableLvl5&6','Lvl5_6','RockTransformsLevel5'),
        ('TableLvl7-8','Lvl7_8','RockTransformsLevel7'),('Table-GameLevel9','Lvl9','RockTransformsLevel9'),
        ('Table-GameLevel9-12Model','Lvl9_12','RockTransformsLevel11'),('Level13Table','Lvl13','RockTransformsLevel13')]
def wv(c):
    pos,tri,nm=mesh_tris(c['meshId']); W=np.array(c['world']); return (np.c_[pos,np.ones(len(pos))]@W.T)[:,:3],tri
def rock_scale(name):
    for k,t in T.items():
        if G[t['go']]['name']==name and t['father']==0:
            c=T[t['ch'][0]]; return float(world(t['ch'][0])[0,:3].dot(world(t['ch'][0])[0,:3])**0.5),float(world(t['ch'][0])[1,3])
    return None,None
out={}
for root,key,rock in TABLES:
    L=[c for c in C if c['root']==root and c['chainActive'] and c['enabled']]
    rails=[];pock=[];cut=[];solid=[];trig=[]
    for c in L:
        if c['kind']!='Mesh': continue
        P,tri=wv(c); lo,hi=P.min(0),P.max(0)
        rec=dict(go=c['go'],tag=c['tag'],layer=c['layer'],material=c['material'],convex=c['convex'],trigger=c['trigger'],
                 bbox=[round(float(v),5) for v in (*lo,*hi)])
        if c['tag']=='Edge' and not c['trigger']: rails.append(rec)
        elif c['tag']=='PocketInside' and c['trigger']: pock.append(rec)
        elif c['tag']=='Cutout' and c['trigger']: cut.append(rec)
        if c['trigger'] and c['tag'] in ('PocketInside','Cutout'):
            tr=dict(rec); tr['verts']=[[round(float(v),5) for v in p_] for p_ in P]; tr['tris']=tri.tolist(); trig.append(tr)
        if not c['trigger']:
            rec['verts']=[[round(float(v),5) for v in p] for p in P]; rec['tris']=tri.tolist(); solid.append(rec)
    bx_=lambda r:(r['bbox'][0],r['bbox'][3]); bz_=lambda r:(r['bbox'][2],r['bbox'][5])
    xc=sum((r['bbox'][0]+r['bbox'][3])/2 for r in rails)/len(rails); zc=sum((r['bbox'][2]+r['bbox'][5])/2 for r in rails)/len(rails)
    zw=[r for r in rails if (r['bbox'][3]-r['bbox'][0])>(r['bbox'][5]-r['bbox'][2])]   # long rails (face normal along z)
    xw=[r for r in rails if r not in zw]
    top=[r for r in zw if (r['bbox'][2]+r['bbox'][5])/2>zc]; bot=[r for r in zw if r not in top]
    lft=[r for r in xw if (r['bbox'][0]+r['bbox'][3])/2<xc]; rgt=[r for r in xw if r not in lft]
    g=dict(
      xl=max(r['bbox'][3] for r in lft), xr=min(r['bbox'][0] for r in rgt),
      zb=max(r['bbox'][5] for r in bot), zt=min(r['bbox'][2] for r in top),
      topSegX=sorted([bx_(r) for r in top]), botSegX=sorted([bx_(r) for r in bot]),
      leftSegZ=sorted([bz_(r) for r in lft]), rightSegZ=sorted([bz_(r) for r in rgt]))
    pk=[]
    for r in pock:
        b=r['bbox']; pk.append(dict(x=(b[0]+b[3])/2,z=(b[2]+b[5])/2,ex=b[3]-b[0],ez=b[5]-b[2]))
    sc,ry=rock_scale(rock)
    out[key]=dict(root=root,rock=rock,ballScale=sc,rackY=ry,rails=g,pockets=pk,railMeshes=[{k:v for k,v in r.items() if k not in('verts','tris')} for r in rails],
                  solid=solid, triggers=trig, materials=sorted({r['material'] for r in rails if r['material']}))
os.makedirs(sys.argv[1] if len(sys.argv)>1 else '.',exist_ok=True)
D=sys.argv[1] if len(sys.argv)>1 else '.'
json.dump(out,open(D+'/pp2_tables.json','w'),separators=(',',':'))
# summary json without triangles
json.dump({k:{kk:vv for kk,vv in v.items() if kk not in('solid','triggers')} for k,v in out.items()},open(D+'/pp2_tables_summary.json','w'),indent=1)
# ---- C++ header
def segs(a): return '{'+','.join('{%.5f,%.5f}'%tuple(s) for s in a)+'}'
H=['// GENERATED by tools/gen_tablegeo.py from data.unity3d (sharedassets0.assets + .resS). Scene (world) coordinates, metres. Do not edit by hand.',
   '#pragma once','#include <vector>','#include <cstdint>','namespace pp2 { namespace geo {','struct Seg { double a, b; };',
   'struct PocketGeo { double x, z, ex, ez; };   // centre and extents of the PocketInside trigger (CheckBall*)',
   'struct TableGeo {','    const char* key; const char* root;','    double ballScale;   // scene lossyScale of the matching RockTransforms child (ball radius = 0.5*scale); the runtime may set another scale','    double xl, xr, zb, zt;     // cushion INNER FACES (x of left/right rails, z of bottom/top rails)',
   '    std::vector<Seg> topX, botX, leftZ, rightZ;   // extent of every Edge rail piece along its wall','    std::vector<PocketGeo> pockets;','};','inline const std::vector<TableGeo>& tables() {','    static const std::vector<TableGeo> T = {']
for k,v in out.items():
    g=v['rails']
    H.append('        {"%s","%s",%.5f, %.5f,%.5f,%.5f,%.5f, %s,%s,%s,%s,'%(k,v['root'],v['ballScale'],g['xl'],g['xr'],g['zb'],g['zt'],segs(g['topSegX']),segs(g['botSegX']),segs(g['leftSegZ']),segs(g['rightSegZ'])))
    H.append('         {'+','.join('{%.5f,%.5f,%.5f,%.5f}'%(p['x'],p['z'],p['ex'],p['ez']) for p in v['pockets'])+'}},')
H+=['    };','    return T;','}','}}']
open(D+'/pp2_tablegeo_data.hpp','w').write('\n'.join(H)+'\n')
for k,v in out.items():
    g=v['rails']; print(k,'ballScale',v['ballScale'],'faces x[%.4f,%.4f] z[%.4f,%.4f]'%(g['xl'],g['xr'],g['zb'],g['zt']),'W=%.4f H=%.4f'%(g['xr']-g['xl'],g['zt']-g['zb']),'pockets',len(v['pockets']),'solid',len(v['solid']))
