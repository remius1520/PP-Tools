#!/usr/bin/env python3
"""P2B: data/pp2_tables.json (read from the game's sharedassets0.assets by gen_tablegeo.py) -> core/sim/pp2_meshdata.hpp
Every solid (non-trigger) collider triangle of every table, world space, metres. Nothing is fitted or rounded beyond 1e-5 m.
Kept: triangles that overlap the ball-height band (rail y-range +-0.10 m). Dropped: exactly-flat faces (|ny| >= 0.9999: bed / rim tops - a flat
face has no horizontal normal, so with the ball's Y frozen it can never change the ball's xz velocity). Per triangle: tag (0 other, 1 Edge, 2 PocketInside)
and material (0 none = PhysX default, 1 Edges_Physics, 2 Pocket_Physics)."""
import os,sys,json,numpy as np
W0=os.environ.get('PP2_WORK',os.path.join(os.path.dirname(os.path.abspath(__file__)),'..'))
D=json.load(open(os.path.join(W0,'data','pp2_tables.json')))
TAG={'Edge':1,'PocketInside':2}; MAT={None:0,'Edges_Physics':1,'Pocket_Physics':2}
out=sys.argv[1] if len(sys.argv)>1 else os.path.join(W0,'core','sim','pp2_meshdata.hpp')
H=['// GENERATED by tools/gen_meshdata.py from data/pp2_tables.json (game files). World space, metres. Do not edit by hand.',
   '#pragma once','#include <cstdint>','namespace pp2 { namespace geo {',
   'struct MeshSrc { const char* key; int nv; const float* v; int nt; const int32_t* t; const uint8_t* tag; const uint8_t* mat; int nz; const float* zv; const int32_t* zt; const int32_t* zs; };']
names=[];nz=[]
for key,t in D.items():
    ys=[(m['bbox'][1],m['bbox'][4]) for m in t['railMeshes']]; lo=min(a for a,b in ys)-0.10; hi=max(b for a,b in ys)+0.10
    V=[];T=[];TG=[];MT=[];rem={}
    for s in t['solid']:
        P=np.array(s['verts'],float);F=np.array(s['tris'],int)
        tg=TAG.get(s['tag'],0); mt=MAT[s['material']]
        for a,b,c in F:
            A,B,C=P[a],P[b],P[c]; n=np.cross(B-A,C-A); nl=np.linalg.norm(n)
            if nl<1e-12: continue
            if abs(n[1])/nl>=0.9999: continue
            if max(A[1],B[1],C[1])<lo or min(A[1],B[1],C[1])>hi: continue
            idx=[]
            for p in (A,B,C):
                k=(round(p[0],5),round(p[1],5),round(p[2],5))
                if k not in rem: rem[k]=len(V); V.append(k)
                idx.append(rem[k])
            T.append(idx); TG.append(tg); MT.append(mt)
    nm='M_'+key
    H.append('static const float %s_v[] = {%s};'%(nm,','.join('%.5f,%.5f,%.5f'%v for v in V)))
    H.append('static const int32_t %s_t[] = {%s};'%(nm,','.join('%d,%d,%d'%tuple(i) for i in T)))
    H.append('static const uint8_t %s_g[] = {%s};'%(nm,','.join(map(str,TG))))
    H.append('static const uint8_t %s_m[] = {%s};'%(nm,','.join(map(str,MT))))
    ZV=[];ZT=[];ZS=[0]
    for tr in [x for x in t['triggers'] if x['tag']=='PocketInside']:   # same order as 'pockets' (zone i == geo pocket i)
        base=len(ZV); ZV+=tr['verts']; ZT+=[[a+base,b+base,c+base] for a,b,c in tr['tris']]; ZS.append(len(ZT))
    H.append('static const float %s_zv[] = {%s};'%(nm,','.join('%.5f,%.5f,%.5f'%tuple(v) for v in ZV)))
    H.append('static const int32_t %s_zt[] = {%s};'%(nm,','.join('%d,%d,%d'%tuple(i) for i in ZT)))
    H.append('static const int32_t %s_zs[] = {%s};'%(nm,','.join(map(str,ZS))))
    nz.append(len(ZS)-1)
    names.append((key,nm,len(V),len(T)))
    print(key,'verts',len(V),'tris',len(T))
H.append('inline const MeshSrc* meshSources(int& n) {')
H.append('    static const MeshSrc S[] = {')
for (key,nm,nv,nt),z in zip(names,nz): H.append('        {"%s",%d,%s_v,%d,%s_t,%s_g,%s_m,%d,%s_zv,%s_zt,%s_zs},'%(key,nv,nm,nt,nm,nm,nm,z,nm,nm,nm))
H+=['    };','    n = (int)(sizeof(S)/sizeof(S[0])); return S;','}','inline const MeshSrc* meshSource(const char* key) { int n; const MeshSrc* s = meshSources(n); for (int i = 0; i < n; ++i) { const char* a = s[i].key; const char* b = key; while (*a && *a == *b) { ++a; ++b; } if (!*a && !*b) return &s[i]; } return nullptr; }','}}']
open(out,'w').write('\n'.join(H)+'\n'); print('wrote',out,os.path.getsize(out)//1024,'KB')
