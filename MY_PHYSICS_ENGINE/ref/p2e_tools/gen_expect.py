#!/usr/bin/env python3
"""Generate native/expect.inc (expected field offsets + method RVAs) from an il2cpp dump.cs.

usage: gen_expect.py dump.cs [-o native/expect.inc]

The payload compares these tables with what the RUNNING game reports (il2cpp_field_get_offset / MethodInfo.methodPointer - base).
Any shift => the game was updated and PP2 goes to safe mode. Regenerate with the new dump.cs after a game update.
Only (name, argc) pairs that are unique inside their class are used for methods (overloads would be ambiguous by name).
"""
import re, sys, hashlib, os, argparse

# classes whose INSTANCE FIELDS are verified (these are the offsets the payload reads)
FIELD_CLASSES = ["CueBallView", "TrajectoryHandler", "CueBall", "Ball", "GameManager", "PhysicsBuilder", "RulesManager",
                 "GamePhysics", "GameTableSetup", "HandlePhysicsCollisions", "BallService", "GameInpusHandler", "MobileStickInput"]
# classes whose METHODS (RVA) are verified (physics + aiming code that later phases read or hook)
METHOD_CLASSES = ["PhysicsBuilder", "PhysicsSolver", "HandlePhysicsCollisions", "GamePhysics", "Ball", "CueBall", "CueBallView", "TrajectoryHandler"]

CLS = re.compile(r'^(?:public |internal |private |protected )?(?:sealed |abstract |static |partial )*(class|struct) ([^\s:/]+)')
NS = re.compile(r'^// Namespace: ?(.*)$')
FLD = re.compile(r'^\t(?:\[[^\]]*\]\s*)?((?:(?:public|private|protected|internal|static|readonly|const|volatile|new)\s+)+)([^;=(]*?)\s([A-Za-z_]\w*); // (0x[0-9A-Fa-f]+)\s*$')
RVA = re.compile(r'^\t// RVA: (0x[0-9A-Fa-f]+) Offset:')
MTH = re.compile(r'^\t((?:(?:public|private|protected|internal|static|virtual|override|abstract|sealed|extern|new|async)\s+)+)(.*?)\s([A-Za-z_]\w*)\((.*)\) \{ \}\s*$')

def argc(params):
    p = params.strip()
    if not p: return 0
    d = 0; n = 1
    for ch in p:
        if ch in '<([': d += 1
        elif ch in '>)]': d -= 1
        elif ch == ',' and d == 0: n += 1
    return n

def main():
    ap = argparse.ArgumentParser(); ap.add_argument('dump'); ap.add_argument('-o', default='native/expect.inc'); a = ap.parse_args()
    fields, methods = [], []
    ns = ''; cur = None; curns = ''; pend_rva = None; mlist = {}
    size = os.path.getsize(a.dump)
    def flush_methods():
        if cur in METHOD_CLASSES and cur in mlist:
            cnt = {}
            for (n_, c_, r_) in mlist[cur]: cnt[(n_, c_)] = cnt.get((n_, c_), 0) + 1
            for (n_, c_, r_) in mlist[cur]:
                if cnt[(n_, c_)] == 1: methods.append((curns, cur, n_, c_, r_))
    seen = set()
    with open(a.dump, encoding='utf-8', errors='replace') as f:
        for ln in f:
            ln = ln.rstrip('\n')
            m = NS.match(ln)
            if m: ns = m.group(1).strip(); continue
            m = CLS.match(ln)
            if m:
                flush_methods(); cur = m.group(2); curns = ns
                if '.' in cur or '<' in cur or '`' in cur: cur = None; pend_rva = None; continue   # nested / generic types are not verified
                if (curns, cur) in seen: cur = None      # a second class with the same name: ambiguous, skip it
                else: seen.add((curns, cur))
                pend_rva = None; continue
            if cur is None: continue
            m = FLD.match(ln)
            if m and cur in FIELD_CLASSES:
                mods, typ, name, off = m.groups()
                if 'static' not in mods and 'const' not in mods: fields.append((curns, cur, name, int(off, 16)))
                continue
            m = RVA.match(ln)
            if m: pend_rva = int(m.group(1), 16); continue
            if pend_rva is not None:
                m = MTH.match(ln)
                if m and cur in METHOD_CLASSES:
                    name = m.group(3)
                    if not name.startswith('.') and '<' not in name: mlist.setdefault(cur, []).append((name, argc(m.group(4)), pend_rva))
                pend_rva = None
    flush_methods()
    with open(a.dump, 'rb') as f:
        h = hashlib.sha1()
        for chunk in iter(lambda: f.read(1 << 20), b''): h.update(chunk)
    out = ['// GENERATED by tools/gen_expect.py from dump.cs - do not edit by hand.',
           '// source: %s  size=%d  sha1=%s' % (os.path.basename(a.dump), size, h.hexdigest()),
           '// fields=%d methods=%d' % (len(fields), len(methods)),
           'static const char* const kExpectSource = "%s sha1=%s";' % (os.path.basename(a.dump), h.hexdigest()[:12]),
           'static const pp2::ExpectField kExpectFields[] = {']
    for (n_, c_, f_, o_) in fields: out.append('    {"%s","%s","%s",0x%X},' % (n_, c_, f_, o_))
    out.append('};'); out.append('static const pp2::ExpectMethod kExpectMethods[] = {')
    for (n_, c_, m_, k_, r_) in methods: out.append('    {"%s","%s","%s",%d,0x%XULL},' % (n_, c_, m_, k_, r_))
    out.append('};')
    open(a.o, 'w').write('\n'.join(out) + '\n')
    print('fields=%d methods=%d -> %s' % (len(fields), len(methods), a.o))
    per = {}
    for x in fields: per[x[1]] = per.get(x[1], 0) + 1
    print('fields per class:', per)
    per = {}
    for x in methods: per[x[1]] = per.get(x[1], 0) + 1
    print('methods per class:', per)

main()
